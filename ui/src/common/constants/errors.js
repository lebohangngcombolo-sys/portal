/**
 * Error codes that trigger automatic logout of the current session.
 */
export const SESSION_INVALIDATING_CODES = Object.freeze([
  ERROR_CODES.UNAUTHORIZED,
  ERROR_CODES.TOKEN_EXPIRED,
  ERROR_CODES.TOKEN_INVALID,
  ERROR_CODES.SESSION_EXPIRED,
]);

/**
 * True if the given code should trigger a logout.
 */
export function isSessionInvalidating(code) {
  return SESSION_INVALIDATING_CODES.includes(code);
}

/**
 * Map HTTP status to a UI error code (best effort).
 */
export function codeFromStatus(status) {
  switch (status) {
    case 400: return ERROR_CODES.BAD_REQUEST;
    case 401: return ERROR_CODES.UNAUTHORIZED;
    case 403: return ERROR_CODES.FORBIDDEN;
    case 404: return ERROR_CODES.NOT_FOUND;
    case 409: return ERROR_CODES.CONFLICT;
    case 422: return ERROR_CODES.UNPROCESSABLE_ENTITY;
    case 429: return ERROR_CODES.TOO_MANY_REQUESTS;
    case 500: return ERROR_CODES.INTERNAL_ERROR;
    case 503: return ERROR_CODES.SERVICE_UNAVAILABLE;
    default:
      if (status === 0) return ERROR_CODES.NETWORK_ERROR;
      return ERROR_CODES.INTERNAL_ERROR;
  }
}